"""Export the randomizer's logic for the logic viewer (docs/logic.html).

    py tools/export_logic.py           # write docs/logic.json
    py tools/export_logic.py --check   # fail if docs/logic.json is out of date (CI runs this)

The logic lives in randomizer/logic.py: a table of milestones (each needs earlier milestones
plus some items) and a rule per location (milestones + items). The world options
(Open Forest, Deku, Door, Fountain) change the milestone table, so the export has one table
per combination of options (16), and every location's rule for each of them. Rules are
stored once in a shared list and referenced by index, which keeps the file small.

Everything here comes from the repository's own data files: no game files are read.
"""
import itertools, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..')
sys.path.insert(0, ROOT)
from randomizer import logic, names, settings as cfg  # noqa: E402

OUT = os.path.join(ROOT, 'docs', 'logic.json')
OPTIONS = cfg.WORLD_OPEN  # open_forest, open_deku, open_door, open_fountain


def combos():
    """Every combination of the open options, keyed by a string of 0/1 in OPTIONS order."""
    for bits in itertools.product('01', repeat=len(OPTIONS)):
        yield ''.join(bits), {k: b == '1' for k, b in zip(OPTIONS, bits)}


def export():
    locs = json.load(open(os.path.join(ROOT, 'data', 'locations.json'), encoding='utf-8'))
    item_name = names.item_names()
    loc_name = names.location_names(locs)

    rules, rule_ix = [], {}

    def rule_id(pre, items):
        key = (tuple(pre), tuple(items))
        if key not in rule_ix:
            rule_ix[key] = len(rules)
            rules.append({'pre': list(pre), 'items': list(items)})
        return rule_ix[key]

    tables, per_loc = {}, {l['id']: [] for l in locs}
    try:
        for key, opts in combos():
            logic.configure(opts)
            tables[key] = [{'id': n, 'pre': list(pre), 'items': list(items)} for n, pre, items in logic.MILESTONES]
            for l in locs:
                pre, items = logic.location_rule(l)
                per_loc[l['id']].append(rule_id(pre, items))
    finally:
        logic.configure({})

    out_locs = []
    for l in locs:
        r = per_loc[l['id']]
        out_locs.append({
            'id': l['id'], 'name': loc_name[l['id']], 'area': l['area'], 'area_name': l['area_name'],
            'kind': l['kind'], 'ages': l['ages'], 'vanilla': l['vanilla'],
            'vanilla_name': item_name.get(l['vanilla'], l['vanilla']),
            # one index when the options don't change this location's rule, else one per combination
            'rule': r[0] if len(set(r)) == 1 else r,
        })

    return {
        'about': 'Generated by tools/export_logic.py from randomizer/logic.py. Do not edit by hand.',
        'options': [{'key': k, 'label': cfg.WORLD[k]['label']} for k in OPTIONS],
        'combos': [k for k, _ in combos()],
        'milestone_labels': logic.MILESTONE_LABELS,
        'items': [{'id': i, 'name': item_name.get(i, i)} for i in logic.PROGRESSION],
        'vanilla_items': sorted(logic.VANILLA_ITEMS),
        'tables': tables,
        'rules': rules,
        'locations': out_locs,
    }


def dump(data):
    return json.dumps(data, ensure_ascii=False, separators=(',', ':'), sort_keys=False) + '\n'


if __name__ == '__main__':
    text = dump(export())
    if '--check' in sys.argv:
        cur = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
        if cur != text:
            sys.exit('docs/logic.json is out of date: run  py tools/export_logic.py')
        print('docs/logic.json is up to date')
    else:
        with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
            f.write(text)
        print('wrote %s (%d KB)' % (os.path.relpath(OUT, ROOT), len(text.encode()) // 1024))
